#!/usr/bin/env python3
"""
fwu_package.py - host-side helper for the firmware-update driver (Python standard library only).

Sub-commands
  build     create a package from an application .bin file: 138-byte manifest + image + summary (.json)
  decode    decode one frame given as hex text or base64 and print its meaning (to read device replies in logs)
  selftest  check this tool against byte vectors produced by the C driver (see gen_vectors.c / selftest_vectors.py)

This tool runs on the host (operator / server side), never on the device. The frame and manifest layouts are
identical to src/frame/fwu_frame.h and src/manifest/fwu_manifest.h; `selftest` compares them with bytes generated by
the C code.

LIMITS
  * Profile DEV: the manifest signature field is written as zero bytes (no signature). A production signature
    (Ed25519) must be added outside this tool; the driver in this repository does not implement Ed25519
    (see docs/KNOWN_ISSUES.md, open issue 37).
  * The tool does not know your flash layout. Pass --max-image-size to make `build` reject images that do not fit
    the staging capacity of your target (see src/config/fwu_layout.h for how the capacity is derived).
"""

import argparse
import base64
import binascii
import hashlib
import json
import os
import struct
import sys

# ------------------------------------------------------------------ constants (identical to the C headers)
SOF = 0xA5
EOF = 0x5A
FRAME_VERSION = 1
FRAME_OVERHEAD = 9              # SOF VER TYPE SEQ LEN(2) ... CRC(2) EOF
FRAME_MAX_PAYLOAD = 512
PROTO_VERSION = 1
MANIFEST_MAGIC = b"FWMF"
MANIFEST_SIZE = 138
MANIFEST_SIGNED_SIZE = 74
DEFAULT_CHUNK = 256

MSG = {
    0x01: "HELLO", 0x02: "AUTH_REQ", 0x03: "AUTH_RESP", 0x10: "REQUEST_DOWNLOAD", 0x11: "TRANSFER_DATA",
    0x12: "TRANSFER_EXIT", 0x13: "ACTIVATE", 0x15: "PULL_START", 0x16: "PULL_QUERY", 0x1F: "ABORT", 0x3E: "KEEPALIVE",
    0x7F: "ERROR", 0x81: "INFO", 0x82: "AUTH_CHALLENGE", 0x83: "AUTH_OK", 0x90: "DOWNLOAD_ACCEPTED",
    0x91: "DATA_ACK", 0x92: "EXIT_PENDING", 0x93: "ACTIVATE_OK", 0x94: "VERIFY_RESULT", 0x95: "PULL_STARTED",
    0x96: "PULL_STATUS", 0x9F: "ABORT_OK", 0xBE: "KEEPALIVE_OK",
}
STATES = {0: "IDLE", 1: "AUTH_PENDING", 2: "AUTHENTICATED", 3: "DOWNLOADING", 4: "VERIFYING", 5: "READY", 6: "COMMITTED"}
ERRORS = {
    10: "INVALID_ARG", 11: "BUFFER_TOO_SMALL", 12: "BAD_STATE", 21: "BUFFER_FULL", 22: "BUFFER_EMPTY", 23: "NOT_ENOUGH_DATA",
    30: "CRC_MISMATCH", 31: "BAD_LENGTH", 32: "BAD_FRAME", 33: "BAD_MANIFEST", 34: "IMAGE_TOO_LARGE", 35: "HASH_MISMATCH",
    40: "FLASH_WRITE", 41: "OUT_OF_RANGE", 42: "WRITE_ALIGNMENT", 43: "ERASE_ALIGNMENT", 44: "FLASH_GEOMETRY",
    45: "FLASH_NOT_ERASED", 46: "FLASH_POWER_LOSS", 47: "FLASH_ERASE", 50: "BAD_SIGNATURE", 51: "CRYPTO_FAILURE",
    52: "PRODUCT_MISMATCH", 53: "VERSION_REJECTED", 54: "KEY_REJECTED", 60: "UNKNOWN_MESSAGE", 61: "BAD_BLOCK",
    62: "LOCKED_OUT", 70: "CONTRACT_MISMATCH",
}


# ------------------------------------------------------------------ frame
def crc16_modbus(data: bytes) -> int:
    crc = 0xFFFF
    for b in data:
        crc ^= b
        for _ in range(8):
            crc = (crc >> 1) ^ 0xA001 if crc & 1 else crc >> 1
    return crc


def frame_encode(msg_type: int, seq: int, payload: bytes) -> bytes:
    if not 1 <= len(payload) <= FRAME_MAX_PAYLOAD:
        raise ValueError("payload length must be 1..512")
    body = bytes([FRAME_VERSION, msg_type & 0xFF, seq & 0xFF]) + struct.pack(">H", len(payload)) + payload
    return bytes([SOF]) + body + struct.pack(">H", crc16_modbus(body)) + bytes([EOF])


def frame_decode(frame: bytes):
    """Return (type, seq, payload); raise ValueError when the frame is invalid."""
    if len(frame) < FRAME_OVERHEAD + 1:
        raise ValueError("frame too short")
    if frame[0] != SOF or frame[-1] != EOF:
        raise ValueError("bad SOF/EOF")
    if frame[1] != FRAME_VERSION:
        raise ValueError("unsupported frame version")
    length = struct.unpack(">H", frame[4:6])[0]
    if length < 1 or length > FRAME_MAX_PAYLOAD or len(frame) != FRAME_OVERHEAD + length:
        raise ValueError("LEN does not match")
    crc_got = struct.unpack(">H", frame[-3:-1])[0]
    if crc16_modbus(frame[1:-3]) != crc_got:
        raise ValueError("CRC mismatch")
    return frame[2], frame[3], frame[6:6 + length]


# ------------------------------------------------------------------ manifest
def build_manifest(product_id: int, image_version: int, image: bytes, key_id: int = 1, key_version: int = 1,
                   commit_hash: bytes = b"", signature: bytes = b"", max_image_size: int = 0) -> bytes:
    if len(image) < 1 or (max_image_size and len(image) > max_image_size):
        raise ValueError("image size must be 1..%d bytes" % max_image_size if max_image_size else "image must not be empty")
    commit_hash = (commit_hash + bytes(20))[:20]
    signature = (signature + bytes(64))[:64]
    m = MANIFEST_MAGIC + bytes([1, key_id & 0xFF]) + b"\x00\x00"
    m += struct.pack(">I", product_id) + struct.pack(">I", image_version) + struct.pack(">H", key_version)
    m += struct.pack(">I", len(image)) + hashlib.sha256(image).digest() + commit_hash + signature
    assert len(m) == MANIFEST_SIZE
    return m


def parse_manifest(m: bytes) -> dict:
    if len(m) != MANIFEST_SIZE or m[:4] != MANIFEST_MAGIC or m[4] != 1 or m[6:8] != b"\x00\x00":
        raise ValueError("invalid manifest structure")
    return {
        "key_id": m[5], "product_id": struct.unpack(">I", m[8:12])[0], "image_version": struct.unpack(">I", m[12:16])[0],
        "key_version": struct.unpack(">H", m[16:18])[0], "image_size": struct.unpack(">I", m[18:22])[0],
        "sha256": m[22:54].hex(), "commit_hash": m[54:74].hex(), "signature_is_zero": m[74:138] == bytes(64),
    }


# ------------------------------------------------------------------ frame description
def describe(msg_type: int, payload: bytes) -> str:
    name = MSG.get(msg_type, "UNKNOWN(0x%02X)" % msg_type)
    if msg_type == 0x81 and len(payload) == 13:
        ver, flags, prod, run, chunk, state = struct.unpack(">BBIIHB", payload)
        return "INFO proto=%d flags=0x%02X (auth=%d signature=%d) product=%d running_version=%d chunk=%d state=%s" % (
            ver, flags, flags & 1, (flags >> 1) & 1, prod, run, chunk, STATES.get(state, state))
    if msg_type == 0x90 and len(payload) == 9:
        chunk, mode, timeout, nxt = struct.unpack(">HBHI", payload)
        return "DOWNLOAD_ACCEPTED chunk=%d mode=%d timeout=%ds next_offset=%d" % (chunk, mode, timeout, nxt)
    if msg_type == 0x91 and len(payload) == 4:
        return "DATA_ACK next_offset=%d" % struct.unpack(">I", payload)
    if msg_type == 0x7F and len(payload) == 2:
        return "ERROR code=%d (%s) request=%s" % (payload[0], ERRORS.get(payload[0], "?"), MSG.get(payload[1], hex(payload[1])))
    if msg_type == 0x94 and len(payload) == 1:
        return "VERIFY_RESULT code=%d%s" % (payload[0], " (VALID)" if payload[0] == 0 else " (%s)" % ERRORS.get(payload[0], "?"))
    if msg_type in (0x92, 0x93, 0x83, 0x9F) and len(payload) == 1:
        return name
    if msg_type == 0xBE and len(payload) == 1:
        return "KEEPALIVE_OK state=%s" % STATES.get(payload[0], payload[0])
    return "%s payload=%s" % (name, payload[:16].hex() + ("..." if len(payload) > 16 else ""))


# ------------------------------------------------------------------ commands
def cmd_build(a):
    image = open(a.image, "rb").read()
    manifest = build_manifest(a.product, a.version, image, a.key_id, a.key_version,
                              bytes.fromhex(a.commit) if a.commit else b"", max_image_size=a.max_image_size)
    base = os.path.join(a.out, os.path.splitext(os.path.basename(a.image))[0] + "_v%d" % a.version)
    os.makedirs(a.out, exist_ok=True)
    open(base + ".manifest", "wb").write(manifest)
    open(base + ".bin", "wb").write(image)
    info = parse_manifest(manifest)
    info.update({"chunk_size": a.chunk, "chunk_count": -(-len(image) // a.chunk),
                 "profile": "DEV (no signature: manifest signature field is zero)"})
    json.dump(info, open(base + ".json", "w"), indent=2)
    print("manifest :", base + ".manifest", "(138 bytes)")
    print("image    :", base + ".bin", "(%d bytes)" % len(image))
    print("summary  :", base + ".json")
    print("chunks   : %d x %d bytes" % (info["chunk_count"], a.chunk))


def cmd_decode(a):
    text = a.data.strip()
    try:
        raw = bytes.fromhex(text.replace(" ", ""))
    except ValueError:
        raw = base64.b64decode(text)
    t, seq, payload = frame_decode(raw)
    print("type=0x%02X seq=%d payload=%d bytes: %s" % (t, seq, len(payload), describe(t, payload)))


def cmd_selftest(_a=None):
    from selftest_vectors import VECTORS   # bytes produced by the C code (see gen_vectors.c)
    ok = True

    def check(name, cond):
        nonlocal ok
        print("[%s] %s" % ("PASS" if cond else "FAIL", name))
        ok = ok and cond

    check("CRC-16/MODBUS('123456789') = 0x4B37", crc16_modbus(b"123456789") == 0x4B37)
    for name, (msg_type, seq, payload_hex, frame_hex) in VECTORS["frames"].items():
        f = frame_encode(msg_type, seq, bytes.fromhex(payload_hex))
        check("frame %s: identical to the bytes produced by the C code" % name, f.hex().upper() == frame_hex)
        check("... decodes to the same (type, seq, payload)", frame_decode(f) == (msg_type, seq, bytes.fromhex(payload_hex)))
    image = bytes((i * 13 + 29) & 0xFF for i in range(700))
    m = build_manifest(12345, 25, image, 1, 1, bytes(0x30 + i for i in range(20)))
    check("manifest: 138 bytes, SHA-256 equals hashlib, fields correct",
          len(m) == 138 and parse_manifest(m)["sha256"] == hashlib.sha256(image).hexdigest()
          and parse_manifest(m)["product_id"] == 12345 and parse_manifest(m)["image_size"] == 700)
    check("manifest bytes identical to the C test world (signature field excluded)", m[:74].hex().upper() == VECTORS["manifest_head74"])
    bad = bytearray(frame_encode(0x01, 1, b"\x01"))
    bad[-3] ^= 1
    try:
        frame_decode(bytes(bad))
        check("corrupt CRC is rejected", False)
    except ValueError:
        check("corrupt CRC is rejected", True)
    try:
        build_manifest(1, 1, b"")
        check("empty image is rejected", False)
    except ValueError:
        check("empty image is rejected", True)
    try:
        build_manifest(1, 1, bytes(10), max_image_size=5)
        check("image above --max-image-size is rejected", False)
    except ValueError:
        check("image above --max-image-size is rejected", True)
    check("INFO decoding", "product=1001" in describe(0x81, struct.pack(">BBIIHB", 1, 0, 1001, 25, 256, 0)))
    check("ERROR decoding (code 61 = BAD_BLOCK)", "BAD_BLOCK" in describe(0x7F, bytes([61, 0x11])))
    print("\nResult: %s" % ("ALL TESTS PASSED" if ok else "FAILURES"))
    return 0 if ok else 1


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="create a package (manifest + image + summary)")
    b.add_argument("image")
    b.add_argument("--product", type=int, required=True)
    b.add_argument("--version", type=int, required=True)
    b.add_argument("--key-id", type=int, default=1)
    b.add_argument("--key-version", type=int, default=1)
    b.add_argument("--commit", default="", help="20-byte commit digest (hex, optional)")
    b.add_argument("--chunk", type=int, default=DEFAULT_CHUNK)
    b.add_argument("--max-image-size", type=int, default=0, help="reject larger images (bytes); 0 = no limit check")
    b.add_argument("--out", default="out")
    b.set_defaults(fn=cmd_build)
    d = sub.add_parser("decode", help="decode one frame (hex or base64) and print its meaning")
    d.add_argument("data")
    d.set_defaults(fn=cmd_decode)
    s = sub.add_parser("selftest", help="check against vectors produced by the C driver")
    s.set_defaults(fn=cmd_selftest)
    a = p.parse_args()
    sys.exit(a.fn(a) or 0)


if __name__ == "__main__":
    main()
