/* Byte vectors produced by the C driver code (used by the selftest of tools/fwu_package.py). */
#include <stdio.h>
#include <string.h>
#include "fwu_frame.h"
#include "fwu_proto.h"
#include "fwu_bytes.h"
#include "fwu_crypto_sim.h"

static void hex(const unsigned char *d, size_t n)
{
    for(size_t i = 0u; i < n; i++) {
        printf("%02X", d[i] & 0xFFu);
    }
}

static void frame_vec(const char *name, unsigned type, unsigned seq, const fwu_byte_t *payload, size_t len)
{
    fwu_byte_t f[FWU_FRAME_MAX_SIZE];
    size_t n = 0u;
    unsigned char tmp[FWU_FRAME_MAX_SIZE];

    (void)fwu_frame_encode((fwu_byte_t)type, (fwu_byte_t)seq, payload, len, f, FWU_FRAME_MAX_SIZE, &n);
    printf("    \"%s\": (0x%02X, %u, \"", name, type, seq);
    for(size_t i = 0u; i < len; i++) {
        tmp[i] = (unsigned char)payload[i];
    }
    hex(tmp, len);
    printf("\", \"");
    for(size_t i = 0u; i < n; i++) {
        tmp[i] = (unsigned char)f[i];
    }
    hex(tmp, n);
    printf("\"),\n");
}

int main(void)
{
    fwu_byte_t p[64];
    size_t n = 0u;
    fwu_proto_info_t info = { 1u, 0u, 1001u, 25u, 256u, 0u };
    fwu_proto_accepted_t acc = { 256u, 0u, 30u, 0u };
    const fwu_byte_t d4[4] = { 1u, 2u, 3u, 4u };
    fwu_byte_t image[700];
    fwu_byte_t head[74];

    printf("# Generated by the C code (gen_vectors.c); do not edit by hand.\nVECTORS = {\n  \"frames\": {\n");
    p[0] = 1u;
    frame_vec("hello_seq1", 0x01u, 1u, p, 1u);
    (void)fwu_proto_encode_info(&info, p, sizeof(p), &n);
    frame_vec("info_seq1", 0x81u, 1u, p, n);
    (void)fwu_proto_encode_accepted(&acc, p, sizeof(p), &n);
    frame_vec("accepted_seq2", 0x90u, 2u, p, n);
    (void)fwu_proto_encode_data(0u, d4, 4u, p, sizeof(p), &n);
    frame_vec("data_seq3_offset0", 0x11u, 3u, p, n);
    (void)fwu_proto_encode_u32(700u, p, sizeof(p), &n);
    frame_vec("exit_seq4_size700", 0x12u, 4u, p, n);
    (void)fwu_proto_encode_error(FWU_ERR_BAD_BLOCK, 0x11u, p, sizeof(p), &n);
    frame_vec("error_seq5_badblock", 0x7Fu, 5u, p, n);
    printf("  },\n");

    /* first 74 bytes of the manifest (the signed part): same rules as tw_make_package in test_world.h */
    for(unsigned i = 0u; i < 700u; i++) {
        image[i] = (fwu_byte_t)((i * 13u + 29u) & 0xFFu);
    }
    memset(head, 0, sizeof(head));
    head[0] = 0x46u; head[1] = 0x57u; head[2] = 0x4Du; head[3] = 0x46u; head[4] = 0x01u; head[5] = 1u;
    fwu_write_u32_big_endian(&head[8], 12345u);
    fwu_write_u32_big_endian(&head[12], 25u);
    head[16] = 0u; head[17] = 1u;
    fwu_write_u32_big_endian(&head[18], 700u);
    fwu_crypto_sim_sha256(image, 700u, &head[22]);
    for(unsigned i = 0u; i < 20u; i++) {
        head[54u + i] = (fwu_byte_t)(0x30u + i);
    }
    {
        unsigned char tmp[74];
        for(unsigned i = 0u; i < 74u; i++) {
            tmp[i] = (unsigned char)head[i];
        }
        printf("  \"manifest_head74\": \"");
        hex(tmp, 74u);
        printf("\",\n}\n");
    }
    return 0;
}
